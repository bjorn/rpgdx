<?php
include_once("includes/main.php");

$contest_id = (int) ($_GET['contest_id'] ?? $_POST['contest_id'] ?? 0);
$categories = $_POST['categories'] ?? null;

// - The voter needs to be logged in
// - The voter most have voted for some categories
// - A contest ID must be specified

if (!$userdata['session_logged_in']) {
	abort_with_error('You have to login to be able to vote!');
}
if (!is_array($categories)) {
	abort_with_error('Somehow your submission lacked the categories.');
}
if (!$contest_id) {
	abort_with_error('No contest_id specified.');
}

function abort_contest_vote_transaction($error)
{
	doQuery('ROLLBACK', 0);
	abort_with_error($error);
}

doQuery('START TRANSACTION');

// Get all the information about the contest and lock its phase.
$result = doQuery(
	"SELECT contest_id, contest_name, contest_description, contest_start, contest_end, contest_status ".
	"FROM ". CONTESTS_TABLE ." ".
	"WHERE contest_id=". $contest_id ." FOR UPDATE"
);

// The contest ID must be valid and voting must be open.
if (!$contest = rpgdx_db_fetch_object($result)) {
	abort_contest_vote_transaction('No such contest, it might have been removed.');
}
if ((int) $contest->contest_status !== CON_VOTING) {
	abort_contest_vote_transaction('Voting is not open for this contest.');
}

// Get and lock all categories belonging to this contest.
$result = doQuery(
	"SELECT category_id ".
	"FROM ". CONTEST_CATEGORIES_TABLE ." ".
	"WHERE category_contest = ". $contest_id ." FOR UPDATE"
);
$valid_categories = array();
while ($category = rpgdx_db_fetch_object($result)) {
	$valid_categories[(int) $category->category_id] = true;
}
$num_categories = count($valid_categories);

// The number of categories voted on must match the number of
// categories of the contest.
if ($num_categories != count($categories)) {
	abort_contest_vote_transaction('Number of categories doesn\'t match.');
}

// Normalize only the canonical integer forms generated by the contest form.
$votes = array();
foreach ($categories as $category_id => $entry_id) {
	if (!is_int($category_id) || $category_id < 1 || !isset($valid_categories[$category_id])) {
		abort_contest_vote_transaction('At least one category you voted for seems to be invalid.');
	}
	if (!is_int($entry_id) &&
		(!is_string($entry_id) || !preg_match('/^(?:-1|[1-9][0-9]*)$/D', $entry_id))) {
		abort_contest_vote_transaction('At least one entry you voted on seems to be invalid.');
	}
	$votes[$category_id] = (int) $entry_id;
}

// Get qualified entries together with their underlying projects. Missing
// projects and disqualified entries are not eligible vote targets.
$result = doQuery(
	"SELECT entry_id, entry_project FROM ". CONTEST_ENTRIES_TABLE ." ".
	"INNER JOIN ". PROJECTS_TABLE ." ON project_id = entry_project ".
	"WHERE entry_disqualified = 0 AND entry_contest = ". $contest_id ." ".
	"AND project_name IS NOT NULL FOR UPDATE"
);
$entry_projects = array();
$qualified_projects = array();
while ($entry = rpgdx_db_fetch_object($result)) {
	$entry_id = (int) $entry->entry_id;
	$project_id = (int) $entry->entry_project;
	$entry_projects[$entry_id] = $project_id;
	$qualified_projects[$project_id] = true;
}

// The voter cannot vote for the same underlying project in different categories.
$projects = array();
$blank_votes = 0;
foreach ($votes as $category_id => $entry_id) {
	if ($entry_id === -1) {
		$blank_votes++;
		continue;
	}
	if (!isset($entry_projects[$entry_id])) {
		abort_contest_vote_transaction('At least one entry you voted on seems to be invalid.');
	}
	$project_id = $entry_projects[$entry_id];
	if (isset($projects[$project_id])) {
		abort_contest_vote_transaction('You cannot vote multiple times for the same project.');
	}
	$projects[$project_id] = $category_id;
}

// Preserve the existing blank choice where enough projects are available;
// when projects are lacking, blanks cannot exceed that shortage.
$qualified_entries = count($qualified_projects);
if ($num_categories - $qualified_entries > 0) {
	if ($blank_votes > $num_categories - $qualified_entries) {
		abort_contest_vote_transaction('Too many blank votes.');
	}
}

// Replace this user's votes as one transaction.
$user_id = (int) $userdata['user_id'];
doQuery(
	"DELETE votes FROM ". CONTEST_VOTES_TABLE ." votes ".
	"INNER JOIN ". CONTEST_CATEGORIES_TABLE ." categories ON vote_category = category_id ".
	"WHERE vote_user = $user_id AND category_contest = $contest_id"
);

foreach ($votes as $category_id => $entry_id) {
	if ($entry_id !== -1) {
		doQuery(
			"INSERT INTO ". CONTEST_VOTES_TABLE ." ".
			"(vote_entry, vote_user, vote_category) VALUES ".
			"($entry_id, $user_id, $category_id)"
		);
	}
}

doQuery('COMMIT');

header("Location: showcontest.php?contest_id=$contest_id");
?>
